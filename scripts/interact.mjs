// Exercises the playground and role-fit check, then screenshots their result states.
import { chromium } from "@playwright/test";
const [out, w = "1440", h = "900"] = process.argv.slice(2);
const b = await chromium.launch({ channel: "chrome" });
const p = await b.newPage({ viewport: { width: +w, height: +h } });
const errors = [];
p.on("pageerror", (e) => errors.push(String(e)));
await p.goto("http://localhost:4321/", { waitUntil: "networkidle" });
const play = p.locator("[data-play]");
await play.scrollIntoViewIfNeeded();
const card = play.locator('[data-card="rerank"]');
const box = await card.boundingBox();
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
await p.mouse.down();
await p.mouse.move(box.x - 120, box.y + 140, { steps: 8 });
await p.mouse.up();
await play.getByRole("button", { name: "Run a request" }).click();
await p.waitForTimeout(4500);
await play.screenshot({ path: `${out}/play_${w}.png` });
const fit = p.locator("[data-fit]");
await fit.scrollIntoViewIfNeeded();
await fit.getByLabel("AI or ML engineering").click();
await p.waitForTimeout(400);
await fit.getByLabel("Reliability in production").click();
await p.waitForTimeout(400);
await fit.getByLabel("A startup or small product team").click();
await p.waitForTimeout(900);
await fit.screenshot({ path: `${out}/fit_${w}.png` });
console.log("mailto:", await fit.locator("[data-mail]").getAttribute("href"));
console.log("errors", errors);
await b.close();
